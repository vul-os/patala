#!/usr/bin/env node
// gen-site-docs.mjs — regenerate the site's documentation bundle from the
// canonical docs/ tree.
//
// WHY THIS EXISTS
//
// site/docs/*.md used to be four hand-maintained markdown files, and docs/
// held two completely different ones. Not stale copies of each other — two
// disjoint sets, so "the documentation" meant something different depending on
// which directory you opened, and the two deepest documents in the repo
// (compensating-payments, shared-economics) were reachable from the site not
// at all.
//
// docs/ is now the single source. site/docs/ is generated: same bytes, plus a
// generated-file banner, plus every link that cannot resolve inside the site
// bundle rewritten to an absolute repo URL — the bundle ships only the docs it
// lists, so a relative link to ../PATALA.md is dead inside it.
//
// The page list below is also the single source for the docs viewer's own
// navigation: this script writes the sidebar markup and the DOCS manifest into
// site/docs.html between marker comments, so the sidebar cannot drift from the
// files that exist.
//
// Usage:
//   node scripts/gen-site-docs.mjs           # rewrite site/docs + site/docs.html
//   node scripts/gen-site-docs.mjs --check   # verify both are current (a gate)
//
// --check exits non-zero and names the file when anything is stale, missing or
// orphaned. It is the anti-rot half; without it the generator is a convenience
// somebody forgets to run.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_URL = 'https://github.com/vul-os/patala/blob/main/';

// ── The page list ──────────────────────────────────────────────────────────
// Order is reading order. `section` groups the sidebar; a page's position in
// this array is its position in the pager (previous / next), so keep a section's
// pages contiguous.
export const PAGES = [
  { file: 'overview.md',              slug: 'overview',      section: 'Start',        title: 'What patala is' },
  { file: 'quickstart.md',            slug: 'quickstart',    section: 'Start',        title: 'Quickstart' },
  { file: 'choosing-a-mode.md',       slug: 'choose',        section: 'Start',        title: 'Choosing a mode' },

  { file: 'rails-interface.md',       slug: 'interface',     section: 'Architecture', title: 'The rail interface' },
  { file: 'polyglot.md',              slug: 'polyglot',      section: 'Architecture', title: 'One core, every language' },
  { file: 'offline-by-default.md',    slug: 'offline',       section: 'Architecture', title: 'The offline default build' },

  { file: 'rust.md',                  slug: 'rust',          section: 'Consuming it', title: 'Rust, embedded' },
  { file: 'python.md',                slug: 'python',        section: 'Consuming it', title: 'Python binding' },
  { file: 'go.md',                    slug: 'go',            section: 'Consuming it', title: 'Go binding' },
  { file: 'language-packages.md',     slug: 'languages',     section: 'Consuming it', title: 'Fifteen language packages' },
  { file: 'c-abi.md',                 slug: 'c-abi',         section: 'Consuming it', title: 'The C ABI' },
  { file: 'sidecar.md',               slug: 'sidecar',       section: 'Consuming it', title: 'The sidecar HTTP API' },

  { file: 'rails-crypto.md',          slug: 'crypto',        section: 'The rails',    title: 'Solana & Stellar' },
  { file: 'rails-fiat.md',            slug: 'fiat',          section: 'The rails',    title: 'Hyperswitch & fiat' },
  { file: 'compensating-payments.md', slug: 'refunds',       section: 'The rails',    title: 'Paying a customer back' },
  { file: 'shared-economics.md',      slug: 'economics',     section: 'The rails',    title: 'Splits & shared economics' },

  { file: 'self-host-vendor.md',      slug: 'self-host',     section: 'Operating',    title: 'Self-host & vendor' },
  { file: 'troubleshooting.md',       slug: 'trouble',       section: 'Operating',    title: 'Troubleshooting' },
  { file: 'status.md',                slug: 'status',        section: 'Operating',    title: 'Status & verification' },
];

const banner = (file) =>
  `<!-- Generated from docs/${file} by \`node scripts/gen-site-docs.mjs\`. Do not edit this file;\n` +
  `     edit docs/${file} and regenerate. \`--check\` fails the build if these drift. -->\n`;

// ── Link rewriting ─────────────────────────────────────────────────────────
// Three cases:
//   1. A link to another page in the bundle stays relative. The viewer turns
//      `foo.md` into `#slug` at render time, and on GitHub it already works.
//   2. Any other relative link is resolved against docs/ and rewritten to an
//      absolute repo URL, because the site bundle does not ship that file.
//   3. Absolute URLs, mailto: and bare fragments are left alone.
const LINK_RE = /\]\(([^)\s]+)(\s+"[^"]*")?\)/g;

function rewriteLinks(body, inBundle) {
  return body.replace(LINK_RE, (whole, target, title = '') => {
    if (/^([a-z][a-z0-9+.-]*:|#|\/\/)/i.test(target)) return whole;
    const [path, frag = ''] = splitFragment(target);
    if (path === '') return whole; // a bare fragment with a title
    const normalized = path.replace(/^\.\//, '');
    if (inBundle.has(normalized)) return `](${normalized}${frag}${title})`;
    const abs = posix.normalize(posix.join('docs', path));
    return `](${REPO_URL}${abs}${frag}${title})`;
  });
}

function splitFragment(target) {
  const i = target.indexOf('#');
  return i === -1 ? [target, ''] : [target.slice(0, i), target.slice(i)];
}

export function generate() {
  const inBundle = new Set(PAGES.map((p) => p.file));
  const out = new Map();
  for (const page of PAGES) {
    const src = readFileSync(join(ROOT, 'docs', page.file), 'utf8');
    out.set(page.file, banner(page.file) + rewriteLinks(src, inBundle));
  }
  return out;
}

// ── The viewer's own navigation ────────────────────────────────────────────
// Written into site/docs.html between markers, so the sidebar, the manifest
// and the files on disk are one fact rather than three.
const NAV_BEGIN = '<!-- BEGIN generated:nav -->';
const NAV_END = '<!-- END generated:nav -->';
const MANIFEST_BEGIN = '// BEGIN generated:manifest';
const MANIFEST_END = '// END generated:manifest';
const NOSCRIPT_BEGIN = '<!-- BEGIN generated:noscript -->';
const NOSCRIPT_END = '<!-- END generated:noscript -->';

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function navMarkup() {
  const lines = [];
  let n = 0;
  let section = null;
  for (const p of PAGES) {
    if (p.section !== section) {
      section = p.section;
      const id = 'dng-' + section.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      lines.push(`      <div class="dn-group" data-group="${id}">`);
      lines.push(
        `        <button class="dn-gtoggle" type="button" aria-expanded="true" aria-controls="${id}">` +
          `<svg class="dn-caret" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m9 6 6 6-6 6"/></svg>` +
          `<span>${esc(section)}</span></button>`
      );
      lines.push(`        <div class="dn-gitems" id="${id}">`);
    }
    n += 1;
    const num = String(n).padStart(2, '0');
    lines.push(
      `          <a data-slug="${p.slug}" href="#${p.slug}">` +
        `<span class="dn-n">${num}</span><span class="dn-t">${esc(p.title)}</span></a>`
    );
    const next = PAGES[PAGES.indexOf(p) + 1];
    if (!next || next.section !== section) lines.push('        </div>');
    if (!next || next.section !== section) lines.push('      </div>');
  }
  return lines.join('\n');
}

export function manifestSource() {
  const rows = PAGES.map(
    (p) =>
      `  {"slug":${JSON.stringify(p.slug)},"title":${JSON.stringify(p.title)},` +
      `"section":${JSON.stringify(p.section)},"path":${JSON.stringify('./docs/' + p.file)}}`
  ).join(',\n');
  return `const DOCS = [\n${rows}\n];`;
}

function spliceRegion(html, begin, end, body, what) {
  const i = html.indexOf(begin);
  const j = html.indexOf(end);
  if (i === -1 || j === -1 || j < i) {
    throw new Error(
      `site/docs.html is missing the ${what} markers (${begin} … ${end}) — ` +
        `the generator cannot write the navigation, so it refuses to guess.`
    );
  }
  return html.slice(0, i + begin.length) + '\n' + body + '\n' + html.slice(j);
}

// The JS-off fallback list. A visitor without JavaScript gets a real index of
// every document rather than a permanent "Loading…" — each file is readable
// text, which is the one case where raw markdown is an acceptable substitute
// for the styled render.
export function noscriptMarkup() {
  let section = null;
  const lines = [];
  for (const p of PAGES) {
    if (p.section !== section) {
      if (section !== null) lines.push('        </ul>');
      section = p.section;
      lines.push(`        <p style="margin:.8em 0 .2em"><b>${esc(section)}</b></p>`);
      lines.push('        <ul style="margin:0;padding-left:1.3em">');
    }
    lines.push(`          <li><a href="./docs/${p.file}">${esc(p.title)}</a></li>`);
  }
  lines.push('        </ul>');
  return lines.join('\n');
}

export function generateDocsHtml() {
  let html = readFileSync(join(ROOT, 'site', 'docs.html'), 'utf8');
  html = spliceRegion(html, NAV_BEGIN, NAV_END, navMarkup(), 'sidebar');
  html = spliceRegion(html, MANIFEST_BEGIN, MANIFEST_END, manifestSource(), 'manifest');
  html = spliceRegion(html, NOSCRIPT_BEGIN, NOSCRIPT_END, noscriptMarkup(), 'noscript index');
  // The document count in the rail's header is part of the same fact.
  html = html.replace(
    /(<span class="dn-count">)[^<]*(<\/span>)/,
    `$1${PAGES.length} documents$2`
  );
  return html;
}

// ── Entry point ────────────────────────────────────────────────────────────
const check = process.argv.includes('--check');
const want = generate();
const siteDocs = join(ROOT, 'site', 'docs');
const problems = [];

if (want.size !== PAGES.length || PAGES.length < 12) {
  problems.push(
    `the generator produced ${want.size} of ${PAGES.length} pages — too few to be a real check`
  );
}

for (const [name, body] of want) {
  const path = join(siteDocs, name);
  let got = null;
  try {
    got = readFileSync(path, 'utf8');
  } catch {
    /* missing */
  }
  if (check) {
    if (got === null) problems.push(`site/docs/${name} is MISSING`);
    else if (got !== body) problems.push(`site/docs/${name} is STALE`);
  } else if (got !== body) {
    writeFileSync(path, body);
    console.log(`  wrote site/docs/${name}`);
  }
}

// No orphans: a file in site/docs that the generator does not produce is a
// hand-maintained copy, and it will rot.
for (const entry of readdirSync(siteDocs)) {
  if (!entry.endsWith('.md') || want.has(entry)) continue;
  problems.push(
    `site/docs/${entry} is not generated from anything — add it to PAGES in ` +
      `scripts/gen-site-docs.mjs or delete it`
  );
}

// A typo'd sibling link is the failure this catches. `[x](rails-fait.md)`
// is not in the bundle, so rewriteLinks turns it into a perfectly well-formed
// absolute GitHub URL that 404s — the rewrite hides the mistake rather than
// surfacing it. So the CANONICAL sources are checked, before rewriting: any
// relative link that resolves inside docs/ must name a file that exists.
//
// (Checking the generated bundle instead would check nothing: every link in it
// is either a bundle sibling or an absolute URL, by construction.)
for (const page of PAGES) {
  const src = readFileSync(join(ROOT, 'docs', page.file), 'utf8');
  for (const m of src.matchAll(LINK_RE)) {
    if (/^([a-z][a-z0-9+.-]*:|#|\/\/)/i.test(m[1])) continue;
    const [path] = splitFragment(m[1]);
    if (path === '' || path.startsWith('../')) continue; // outside docs/: rewritten, not ours to resolve
    const target = join(ROOT, 'docs', path.replace(/^\.\//, ''));
    try {
      readFileSync(target);
    } catch {
      problems.push(`docs/${page.file} links to ${m[1]}, which does not exist in docs/`);
    }
  }
}

const htmlWant = generateDocsHtml();
const htmlPath = join(ROOT, 'site', 'docs.html');
const htmlGot = readFileSync(htmlPath, 'utf8');
if (check) {
  if (htmlGot !== htmlWant) {
    problems.push('site/docs.html\'s generated navigation is STALE');
  }
} else if (htmlGot !== htmlWant) {
  writeFileSync(htmlPath, htmlWant);
  console.log('  wrote site/docs.html (navigation + manifest)');
}

if (problems.length) {
  console.error('gen-site-docs: FAIL');
  for (const p of problems) console.error(`  · ${p}`);
  console.error(
    check
      ? '\ndocs/ is the single source of truth. Run `node scripts/gen-site-docs.mjs`.'
      : ''
  );
  process.exit(1);
}

console.log(
  check
    ? `gen-site-docs: OK — ${PAGES.length} pages in site/docs are current with docs/`
    : `gen-site-docs: OK — ${PAGES.length} pages generated`
);
